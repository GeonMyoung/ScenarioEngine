"""MQTT-private traced copies of the adopted generated decoder; no SDK edits.

Retain the source checks verbatim and annotate their call boundaries only.
Regeneration fails when the input does not match the supported generated shape.
"""
import hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
source=ROOT/'GitsnAsnUtil/src/GitsnAsn1.c'
text=source.read_text(encoding='cp949')
functions={m[1]:(m[0].split('\n{')[0],m[0]) for m in re.finditer(r'^int (ASN1_(?:CHECK_|PER_UNAlign_(?:Data_)?Dec_)\w+)\([^\n]+\)\n\{.*?^\}',text,re.M|re.S)}
roots=['MessageFrame','BasicSafetyMessage','SPAT','TrafficLightStatusMessage','TravelerInformation','TravelerInformation_KOR','GeographicalPath_KOR']
needed={'ASN1_PER_UNAlign_Dec_'+t for t in roots}
todo=list(needed)
while todo:
    name=todo.pop()
    assert name in functions,name
    for dep in re.findall(r'\bASN1_\w+(?=\()',functions[name][1]):
        if dep in functions and dep not in needed:needed.add(dep);todo.append(dep)
rename={n:'MqttTrace_'+n for n in needed}
aliases='/* Generated by tools/generate_diagnostics.py. */\n#pragma once\n'
aliases+='\n'.join('#define '+n+' '+rename[n] for n in sorted(needed))+'\n'
(ROOT/'mqttv2nconformance/src/MqttTraceAliases.h').write_text(aliases,encoding='ascii')
out=['/* Generated from adopted GitsnAsn1.c; MQTT private diagnostic symbols. */',
     '#include "MqttTraceAliases.h"','#include <GitsnAsnUtil.h>','#include "MqttDiagnostics.h"',
     '#define ASN1_CHECK_INTEGER(v,c) MqttDiag_check_integer(v,c,sizeof(c))',
     '#define ASN1_CHECK_ENUMERATED(v,c) MqttDiag_check_enum(v,c,sizeof(c))']
out.extend(functions[n][0]+';' for n in sorted(needed))
annotated=0
for name in sorted(needed):
    header,body=functions[name]
    ischeck=name.startswith('ASN1_CHECK_')
    def call(m):
        global annotated
        indent,expr=m[1],m[2]
        fields=re.findall(r'value->([A-Za-z_][A-Za-z_0-9]*)',expr)
        field=fields[0] if fields else ''
        indexed='pdata' in expr and not ischeck or 'pnode->data' in expr and ischeck
        index='value->count-count+1' if ischeck else 'value->count+1'
        push=f'MqttDiag_enter("{field}", {index if indexed else 0})'
        ws='NULL' if ischeck else 'workspace'
        annotated+=1
        return (indent+'{ size_t saved='+push+';\n'+indent+'  ret='+expr+';\n'+indent+
                f'  if(ret<0) MqttDiag_failure({ws});\n'+indent+'  MqttDiag_leave(saved);\n'+indent+'  if(ret<0) return ret; }')
    body=re.sub(r'(?m)^(\s*)if \(\(ret = (ASN1_\w+\([^\n]+\))\) < 0\) return ret;',call,body)
    out.append(body)
(ROOT/'mqttv2nconformance/src/MqttTracedDecoder.c').write_text('\n'.join(out)+'\n',encoding='ascii')
manifest=dict(source='GitsnAsnUtil/src/GitsnAsn1.c',sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),
              roots=roots,functions=len(needed),annotatedCalls=annotated,sharedSourceModified=False)
(ROOT/'mqttv2nconformance/diagnostic-source.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
print(manifest)
