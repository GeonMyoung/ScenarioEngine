static Dz1TaskProcStatus _test_sample2(void* uArg, void* uRsc, void* timer, Dz1TaskSigMsg** sg, Dz1Error* errp)
{
	Dz1TaskProcStatus ret = Dz1TaskProcStatus_processed;

	
	DatexDataPacket ddp;
	ASN1WorkSpace ws;
	ASN1_INIT_WS_INFO(&ws);
	pthread_cleanup_push(ASN1_INIT_WS_INFO_cancel, (void*)&ws);
	
	if (0) {}
	else if (ASN1_SET_DatexDataPacket_datex_Version_number(&ws, &ddp, 1) < 0) ERR_SET_OUT(errp, EFAULT);
	else if (ASN1_SET_DatexDataPacket_datex_Data(&ws, &ddp, sample_datex_data, 10) < 0) ERR_SET_OUT(errp, EFAULT);
	else if (ASN1_SET_DatexDataPacket_datex_Crc_nbr(&ws, &ddp, sample_crc, 2) < 0) ERR_SET_OUT(errp, EFAULT);
	else
	{
		ASN1_Print_DatexDataPacket(&ddp, 0);
		ssize_t sz = -1;
		Dz1Binary* enc = NULL;

		if ((sz = ASN1_BER_Enc_DatexDataPacket(&ws, &ddp, ASN1IMPL) < 0)) ERR_SET_OUT(errp, EFAULT);
		if ((enc = Dz1Binary_new(ASN1WorkSpace_getEncodePtr(&ws), ASN1WorkSpace_getEncodedSize(&ws, Dz1Asn1Codec_ber), errp)) == NULL) ERR_OUT(errp);
		else
		{
			Dz1Binary_dump(enc, 0);

			const char* path = "DatexDataPacket.ber"; // 원하는 파일명/경로로 변경 가능

			FILE* fp = fopen(path, "wb"); // 바이너리 모드 중요!
			if (!fp) {
				perror("fopen failed");
				return 1;
			}

			size_t need = enc->size;
			size_t wrote = fwrite(enc->data, 1, need, fp);
			if (wrote != need) {
				perror("fwrite failed");
				fclose(fp);
				return 2;
			}
			if (fclose(fp) != 0) {
				perror("fclose failed");
				return 3;
			}
		}
	}
	pthread_cleanup_pop(1); // (ASN1_INIT_WS_INFO_cancel, (void*)&ws);
	return ret;
}

